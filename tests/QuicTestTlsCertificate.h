class QuicTestTlsFile {
public:
    QuicTestTlsFile(const char *tag, std::string_view contents) {
        path_ = "/tmp/fiber_quic_";
        path_.append(tag);
        path_.push_back('_');
        path_.append(std::to_string(static_cast<long>(::getpid())));
        path_.push_back('_');
        path_.append(std::to_string(static_cast<long>(::random())));
        path_.append(".pem");
        std::ofstream out(path_, std::ios::binary);
        if (!out) {
            path_.clear();
            return;
        }
        out.write(contents.data(), static_cast<std::streamsize>(contents.size()));
        if (!out.good()) {
            out.close();
            ::unlink(path_.c_str());
            path_.clear();
        }
    }

    QuicTestTlsFile(const QuicTestTlsFile &) = delete;
    QuicTestTlsFile &operator=(const QuicTestTlsFile &) = delete;
    ~QuicTestTlsFile() {
        if (!path_.empty()) {
            ::unlink(path_.c_str());
        }
    }

    [[nodiscard]] bool valid() const noexcept { return !path_.empty(); }
    [[nodiscard]] const std::string &path() const noexcept { return path_; }

private:
    std::string path_{};
};

